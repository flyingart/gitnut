import { existsSync, statSync } from "node:fs";
import { join, normalize, resolve, sep } from "node:path";
import { IS_COMPILED } from "./version";

/** Web client files: URL path (`/index.html`) -> file path (on disk or inside the compiled binary). */
export type WebAssets = Map<string, string>;

const devDir = resolve(import.meta.dir, "../../web/dist");

/** GITNUT_WEB_DIR, else the assets embedded by scripts/build-daemon.ts, else packages/web/dist in dev. */
export async function loadWebAssets(): Promise<{ dir: string | null; embedded: WebAssets | null }> {
  const hasIndex = (d: string) => existsSync(join(d, "index.html"));
  if (process.env.GITNUT_WEB_DIR) {
    const dir = resolve(process.env.GITNUT_WEB_DIR);
    return { dir: hasIndex(dir) ? dir : null, embedded: null };
  }
  if (IS_COMPILED) {
    try {
      // biome-ignore lint/suspicious/noTsIgnore: generated by scripts/build-daemon.ts, exists only in builds (ts-expect-error would fail there)
      // @ts-ignore
      const mod = await import("./generated/web-assets.ts");
      const map: WebAssets = new Map(Object.entries(mod.default as Record<string, string>));
      return { dir: null, embedded: map.size ? map : null };
    } catch {
      return { dir: null, embedded: null };
    }
  }
  return { dir: hasIndex(devDir) ? devDir : null, embedded: null };
}

const NOT_BUILT = `<!doctype html><meta charset="utf-8"><title>gitnut</title>
<body style="font:15px system-ui;background:#111;color:#ddd;display:grid;place-items:center;height:100vh;margin:0">
<div><h1>gitnut daemon is running</h1><p>The web client isn't built. Run <code>bun run build:web</code>, or connect with the desktop app.</p></div>`;

/** Serve a web asset with SPA fallback to index.html. */
export function serveWeb(web: { dir: string | null; embedded: WebAssets | null }, pathname: string): Response {
  let path = normalize(decodeURIComponent(pathname)).replace(/\\/g, "/");
  if (path.endsWith("/")) path += "index.html";
  let file = lookup(web, path);
  // Unknown paths without an extension are client routes.
  if (!file && !/\.[a-z0-9]+$/i.test(path)) file = lookup(web, "/index.html");
  if (!file) {
    if (!web.dir && !web.embedded) return new Response(NOT_BUILT, { headers: { "content-type": "text/html; charset=utf-8" } });
    return new Response("not found", { status: 404 });
  }
  const hashed = /[-.][A-Za-z0-9_]{8,}\.(js|css|woff2?|png|svg|jpg|webp|wasm)$/.test(path) || path.startsWith("/assets/");
  return new Response(Bun.file(file), {
    headers: { "cache-control": hashed && !path.endsWith(".html") ? "public, max-age=31536000, immutable" : "no-cache" },
  });
}

function lookup(web: { dir: string | null; embedded: WebAssets | null }, path: string): string | null {
  if (web.embedded) return web.embedded.get(path) ?? null;
  if (!web.dir) return null;
  const full = join(web.dir, path);
  if (!full.startsWith(web.dir + sep)) return null;
  try {
    return statSync(full).isFile() ? full : null;
  } catch {
    return null;
  }
}
