#!/usr/bin/env bun
// Build the gitnut daemon/CLI as single-file binaries (R-DAEMON-1).
//   bun run scripts/build-daemon.ts [--targets host|all|linux-x64,darwin-arm64,...] [--out dist/bin]
//                                   [--version X] [--no-web] [--build-web] [--web-dir DIR]
// Embeds packages/web/dist (when present) through a generated module of `type: "file"` imports,
// so the binary serves the web client with its original relative paths.
// Bakes in version and GITNUT_SITE_URL (the website: updates come from <site>/manifest.json) with
// --define. GITNUT_SITE_URL is required (put it in .env, Bun loads it) so every shipped binary can
// update; --dev builds without it (updates off).
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";
import { PLATFORMS, binaryName, platformOf, type Platform } from "../packages/commons/src/platform";

const ROOT = resolve(import.meta.dir, "..");
const DAEMON = join(ROOT, "packages", "daemon");
const GENERATED = join(DAEMON, "src", "generated");

const { values } = parseArgs({
  options: {
    targets: { type: "string", default: "host" },
    out: { type: "string", default: "dist/bin" },
    version: { type: "string" },
    "no-web": { type: "boolean", default: false },
    "build-web": { type: "boolean", default: false },
    "web-dir": { type: "string", default: "packages/web/dist" },
    dev: { type: "boolean", default: false },
  },
});

const site = process.env.GITNUT_SITE_URL?.replace(/\/+$/, "") ?? "";
if (!site && !values.dev) {
  console.error("Set GITNUT_SITE_URL in the environment or .env, so the binary knows where updates come from.\nFor a local build without updates add --dev.");
  process.exit(1);
}

const host = platformOf(process.platform, process.arch);
const targets: Platform[] =
  values.targets === "all" ? PLATFORMS : values.targets === "host" ? [host!] : (values.targets!.split(",").map((t) => t.trim()) as Platform[]);
for (const t of targets) if (!PLATFORMS.includes(t)) throw new Error(`unknown target ${t} (known: ${PLATFORMS.join(", ")})`);

const version = values.version ?? (await Bun.file(join(ROOT, "package.json")).json()).version;
const out = resolve(ROOT, values.out!);
const WEB_DIST = resolve(ROOT, values["web-dir"]!);

function run(cmd: string[], cwd = ROOT) {
  console.log(`$ ${cmd.join(" ")}`);
  const r = Bun.spawnSync(cmd, { cwd, stdout: "inherit", stderr: "inherit" });
  if (r.exitCode !== 0) throw new Error(`failed: ${cmd.join(" ")}`);
}

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? files(p) : [p];
  });
}

if (values["build-web"] && !values["no-web"]) run(["bun", "run", "--cwd", "packages/web", "build"]);

// Generated module: URL path -> embedded file path. Empty map = no web client in this build.
rmSync(GENERATED, { recursive: true, force: true });
mkdirSync(GENERATED, { recursive: true });
let web: string[] = [];
try {
  web = values["no-web"] ? [] : files(WEB_DIST);
} catch {}
const lines = web.map((f, i) => `import f${i} from ${JSON.stringify(relative(GENERATED, f).replace(/\\/g, "/"))} with { type: "file" };`);
const entries = web.map((f, i) => `  ${JSON.stringify(`/${relative(WEB_DIST, f).replace(/\\/g, "/")}`)}: f${i},`);
writeFileSync(
  join(GENERATED, "web-assets.ts"),
  `// @ts-nocheck\n// Generated by scripts/build-daemon.ts. Do not edit.\n${lines.join("\n")}\nexport default {\n${entries.join("\n")}\n} as Record<string, string>;\n`,
);
console.log(web.length ? `embedding ${web.length} web files from ${relative(ROOT, WEB_DIST)}` : "no web client embedded");

const define = (k: string, v: string) => ["--define", `${k}=${JSON.stringify(v)}`];
mkdirSync(out, { recursive: true });
for (const t of targets) {
  const file = join(out, binaryName(t));
  run([
    "bun",
    "build",
    "--compile",
    "--minify",
    `--target=bun-${t}`,
    ...define("GITNUT_VERSION", version),
    ...define("GITNUT_SITE_URL", site),
    join(DAEMON, "src", "cli.ts"),
    "--outfile",
    file,
  ]);
  console.log(`built ${relative(ROOT, file)} (${(statSync(file).size / 1e6).toFixed(1)} MB)`);
}
